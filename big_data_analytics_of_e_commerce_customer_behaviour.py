def get_process_memory_mb():

    process = psutil.Process(
        os.getpid()
    )

    return (
        process.memory_info().rss
        / (1024 ** 2)
    )


def get_available_memory_mb():

    return (
        psutil.virtual_memory().available
        / (1024 ** 2)
    )


