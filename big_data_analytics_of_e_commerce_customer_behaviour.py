# 10. OPERATION 1
# EVENT DISTRIBUTION
# ============================================================

def event_distribution(df):

    result = (

        df
        .groupby(
            "event_type",
            dropna=False
        )
        .size()
        .reset_index(
            name="event_count"
        )

    )


    total_events = len(df)


    result["percentage"] = (

        result["event_count"]
        / total_events
        * 100

    ).round(2)


    result = (

        result
        .sort_values(
            "event_count",
            ascending=False
        )
        .reset_index(
            drop=True
        )

    )


    return result


