# ============================================================

def top10_brands(df):

    # Select purchase events
    purchases = (

        df.loc[
            df["event_type"] == "purchase",
            [
                "brand",
                "price"
            ]
        ]
        .copy()

    )


    # Remove missing / blank brands
    purchases = (

        purchases.loc[

            purchases["brand"].notna()
            &
            (
                purchases["brand"]
                .str.strip()
                != ""
            )

        ]
        .copy()

    )


    # Invalid price values are ignored
    # for revenue and average calculations.

    purchases["valid_price"] = (

        purchases["price"]
        .where(

            purchases["price"].notna()
            &
            (purchases["price"] > 0)

        )

    )


    result = (

        purchases

        .groupby(
            "brand"
        )

        .agg(

            estimated_revenue=(
                "valid_price",
                "sum"
            ),

            num_purchase_events=(
                "brand",
                "size"
            ),

            avg_purchase_event_value=(
                "valid_price",
                "mean"
            )

        )

        .reset_index()

    )


    result[
        "estimated_revenue"
    ] = (

        result[
            "estimated_revenue"
        ].round(2)

    )


    result[
        "avg_purchase_event_value"
    ] = (

        result[
            "avg_purchase_event_value"
        ].round(2)

    )


    result = (

        result

        .sort_values(
            "estimated_revenue",
            ascending=False
        )

        .head(10)

        .reset_index(
            drop=True
        )

    )


    return result


