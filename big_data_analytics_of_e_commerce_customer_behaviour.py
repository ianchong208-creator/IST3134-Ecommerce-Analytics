# 11. OPERATION 2
# DAILY PURCHASE AND REVENUE ANALYSIS
# ============================================================

def daily_purchase_revenue(df):

    # Select purchase events
    purchases = (

        df.loc[
            df["event_type"] == "purchase",
            [
                "event_time",
                "event_type",
                "price"
            ]
        ]
        .copy()

    )


    # Extract YYYY-MM-DD from event_time
    purchases["event_date"] = (

        purchases["event_time"]
        .str.slice(
            0,
            10
        )

    )


    # Invalid prices are excluded from
    # revenue and average calculations.
    # Purchase-event count still counts
    # all purchase events.

    purchases["valid_price"] = (

        purchases["price"]
        .where(

            purchases["price"].notna()
            &
            (purchases["price"] > 0)

        )

    )


    result = (

        purchases
        .groupby(
            "event_date"
        )
        .agg(

            num_purchase_events=(
                "event_type",
                "size"
            ),

            estimated_revenue=(
                "valid_price",
                "sum"
            ),

            avg_purchase_event_value=(
                "valid_price",
                "mean"
            )

        )
        .reset_index()
        .sort_values(
            "event_date"
        )

    )


    result["estimated_revenue"] = (

        result[
            "estimated_revenue"
        ].round(2)

    )


    result[
        "avg_purchase_event_value"
    ] = (

        result[
            "avg_purchase_event_value"
        ].round(2)

    )


    return result


